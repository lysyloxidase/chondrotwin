#!/usr/bin/env python
"""Stage 1 of the open-data knee simulation: calibrate the agent-based model on open data and test it out of sample.

Usage:  python scripts/fetch_data.py            # once (~93 MB; see DATA.md for licenses)
        python scripts/knee_open_data.py [--out docs/knee_open_data.md] [--recompute]

Writes a Markdown report with every number computed here; intermediate tables go to data/derived/.
Runtime: ~1 min with cached derived data, ~12 min with --recompute (geometry of 507 knees, ABM dose-response).
"""
import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

from chondrotwin import ConfinedCompression, datasets
from chondrotwin.knee import loads as L
from chondrotwin.knee.analysis import (abm_stage_composition, adjusted_kl_effects, marker_detection, mixture_test,
                                       observed_losses, stage_ratio_bootstrap, tissue_test)
from chondrotwin.knee.cells import composition_by_stage, ji2019_cells
from chondrotwin.knee.erosion import curve, dose_response
from chondrotwin.knee.geometry import tibial_geometry
from chondrotwin.knee.report import table

ROOT = Path(__file__).resolve().parents[1]
DERIVED = datasets.data_dir().parent / "derived"
H_MED, H_LAT = 2.2, 2.6          # mm; train KL0 central thickness (2.22 / 2.58), rounded to the 0.1 mm voxel
YEAR = 5
out = []


def md(s=""):
    print(s)
    out.append(s)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", default=str(ROOT / "docs" / "knee_open_data.md"))
    p.add_argument("--recompute", action="store_true", help="ignore cached derived tables")
    a = p.parse_args()
    if a.recompute:
        for f in ("oaizib_cm_tibia.csv", "abm_dose_response.csv"):
            (DERIVED / f).unlink(missing_ok=True)
    t0 = time.perf_counter()

    md("# Knee cartilage simulation from open data — stage 1 results")
    md()
    md("_Generated by `scripts/knee_open_data.py`; do not edit by hand. Data sources, licenses and citations: `DATA.md`._")
    md()

    # ---------------------------------------------------------------- 1. loads
    loads = L.load_all()
    l_cal = L.calibrate_condylar_distance(loads)
    summ = L.summary(loads, l_cal)
    md("## 1. In vivo knee loads (OrthoLoad, 8 subjects with instrumented knee replacements, level walking)")
    md()
    md(f"Condylar distance calibrated to the published medial peaks (Kutzner et al. 2013: 1.76 / 1.87 BW): "
       f"**l = {l_cal * 1000:.1f} mm**. Resulting mean medial peaks: "
       f"{summ.peak_medial_early_BW.mean():.2f} ± {summ.peak_medial_early_BW.std():.2f} / "
       f"{summ.peak_medial_late_BW.mean():.2f} ± {summ.peak_medial_late_BW.std():.2f} BW.")
    md()
    md(table(summ[["body_weight_N", "varus_deg", "peak_total_BW", "mean_total_BW", "mean_medial_BW", "mean_lateral_BW",
                   "medial_ratio"]]))
    md()
    md(f"Medial share of the axial force over the gait cycle: **{summ.medial_ratio.mean():.2f} ± {summ.medial_ratio.std():.2f}** "
       f"(range {summ.medial_ratio.min():.2f}–{summ.medial_ratio.max():.2f}; the only valgus knee, K6L, is the lowest).")
    md()

    # ---------------------------------------------------------------- 2. bridge check
    g = loads["K5R"]
    T = g.cycle_time
    tt = g.t - g.t[0]
    wave = lambda t: 2.0e6 * np.interp(t % T, tt, g.Fz) / g.Fz.max()   # noqa: E731
    tis = ConfinedCompression()
    cyc = tis.solve_history(wave, t_end=3 * tis.tau, dt_max=T / 40, n_out=50)
    const = tis.solve(cyc.sigma0, t_end=3 * tis.tau, n_out=50)
    rel = abs(cyc.u[-1, -1] - const.u[-1, -1]) / abs(const.u[-1, -1])
    md("## 2. Mechanical bridge: time averaging")
    md()
    md(f"Biphasic confined compression (τ = {tis.tau:.0f} s) under the measured gait waveform for 3τ versus a constant "
       f"stress equal to its time average: surface displacement differs by **{100 * rel:.1f} %**. The ABM is therefore driven "
       f"by a daily effective stress σ = κ · (cycle-mean compartment force) / (plate area), with κ calibrated below.")
    md()

    # ---------------------------------------------------------------- 3. geometry
    geo = tibial_geometry(progress=True)
    md("## 3. Tibial cartilage in 507 OAI knees (OAIZIB-CM)")
    md()
    by_kl = geo.groupby("KLGrade").agg(n=("split", "size"), BMI=("BMI", "mean"), age=("Age", "mean"),
                                       medial_central_mm=("medial_central_thickness_mm", "mean"),
                                       lateral_central_mm=("lateral_central_thickness_mm", "mean"),
                                       medial_denuded_mm2=("medial_denuded_mm2", "mean"),
                                       lateral_denuded_mm2=("lateral_denuded_mm2", "mean"))
    by_kl.index = by_kl.index.astype(int)
    md(table(by_kl))
    md()
    md(f"{int(geo.KLGrade.isna().sum())} knees have no KL grade and are excluded from KL analyses. "
       "Adjusted KL effects on central thickness (OLS with sex, BMI, age; all knees; mm, mean ± SE):")
    md()
    eff = pd.concat({side: adjusted_kl_effects(geo, f"{side}_central_thickness_mm")[["effect", "se"]]
                     for side in ("medial", "lateral")}, axis=1)
    eff.columns = [f"{s} {c}" for s, c in eff.columns]
    md(table(eff))
    md()
    md("Note the thickening at KL 2 in both plates (about 2 SE; early-OA swelling), which the model does not represent.")
    md()
    obs = observed_losses(geo)
    md("Observed central thickness loss, KL4 vs KL0 (adjusted), by split:")
    md()
    md(table(obs.set_index(["split"])))
    md()

    # ---------------------------------------------------------------- 4. tissue test
    sig = np.round(np.arange(0.060, 0.1601, 0.005), 3)
    cache = DERIVED / "abm_dose_response.csv"
    if cache.exists():
        dose = pd.read_csv(cache)
    else:
        dose = pd.concat([dose_response(sig, h, years=YEAR, seeds=(0, 1)) for h in (H_MED, H_LAT)], ignore_index=True)
        cache.parent.mkdir(parents=True, exist_ok=True)
        dose.to_csv(cache, index=False)
    s_m, e_m = curve(dose, H_MED, YEAR)
    md("## 4. Tissue test: calibrate on the medial plate (train), predict the lateral plate")
    md()
    md(f"ABM dose–response after {YEAR} simulated years (eroded depth = depth with voxel matrix < 0.3; 2 seeds): "
       f"no erosion up to {s_m[np.argmax(e_m > 0) - 1]:.3f} MPa, then "
       + ", ".join(f"{e:.2f} mm at {s:.3f}" for s, e in zip(s_m, e_m) if e > 0 and round(s * 1000) % 20 == 0) + " MPa (medial plate, h = 2.2 mm).")
    md()
    rows = []
    for lval in (0.040, l_cal, 0.055):
        mr = L.summary(loads, lval).medial_ratio.values
        for yr in (2, YEAR):
            r = mixture_test(geo, mr, dose, H_MED, H_LAT, yr)
            rows.append({"l (mm)": f"{lval * 1000:.0f}", "ABM years": yr, "calibrated load scale (MPa)": r["load_scale_MPa"],
                         "mean medial loss (calibrated)": r["mean_medial_loss_mm"],
                         "predicted mean lateral loss": r["predicted_mean_lateral_loss_mm"]})
    mix = pd.DataFrame(rows).set_index("l (mm)")
    md("Population mixture (each KL4 knee assigned one of the 8 in vivo medial shares; common load level calibrated "
       "so that the mean medial loss equals the train-split value):")
    md()
    md(table(mix))
    md()
    o = obs.set_index(["split", "compartment"])
    lat_pred = float(mix["predicted mean lateral loss"].max())
    md("| comparison | observed (mm) | model (mm) | z |")
    md("|---|---|---|---|")
    for split in ("train", "test"):
        ol, se = o.loc[(split, "lateral"), "loss_mm"], o.loc[(split, "lateral"), "se_mm"]
        md(f"| lateral loss, {split} | {ol:.3f} ± {se:.3f} | ≤ {lat_pred:.3f} | {(ol - lat_pred) / se:.2f} |")
    om, sem = o.loc[("test", "medial"), "loss_mm"], o.loc[("test", "medial"), "se_mm"]
    md(f"| medial loss, test (not used for calibration) | {om:.3f} ± {sem:.3f} | {o.loc[('train', 'medial'), 'loss_mm']:.3f} | "
       f"{(om - o.loc[('train', 'medial'), 'loss_mm']) / sem:.2f} |")
    md()
    tt_ = tissue_test(geo, {**summ.medial_ratio.to_dict()}, dose, H_MED, H_LAT, YEAR)
    md(f"Single-knee view (calibrated medial stress {tt_.sigma_medial_MPa.iloc[0]:.3f} MPa): lateral stress "
       f"{tt_.sigma_lateral_MPa.min():.3f}–{tt_.sigma_lateral_MPa.max():.3f} MPa; only the valgus knee (K6L) exceeds the "
       f"lateral threshold, and it is then predicted to lose {tt_.predicted_lateral_loss_mm.max():.2f} mm laterally — "
       f"valgus → lateral disease, as observed clinically.")
    md()

    # ---------------------------------------------------------------- 5. cell test
    cells = ji2019_cells()
    umi = pd.read_csv(datasets.require("gse104782", "GSE104782_allcells_UMI_count.txt.gz"), sep="\t", index_col=0)
    genes = ["RUNX2", "MMP13", "COL10A1", "CDKN2A", "SOX9", "ACAN"]
    det = marker_detection(umi, cells, genes)
    ratios = pd.DataFrame([stage_ratio_bootstrap(det, gname) for gname in genes]).set_index("gene")
    early = pd.DataFrame([{"gene": gname, "stage": st, **{k: v for k, v in stage_ratio_bootstrap(det, gname, stage=st).items()
                                                          if k in ("ratio", "ci_low", "ci_high")}}
                          for gname in ("CDKN2A", "RUNX2", "MMP13") for st in (1, 2, 3)]).set_index("gene")
    abm = abm_stage_composition()
    abm["n"] = abm["n"].astype(int)
    md("## 5. Cell test: chondrocyte states by degeneration stage (GSE104782 vs ABM)")
    md()
    md("Published cluster composition (authors' labels mapped to model fates; see `chondrotwin/knee/cells.py`):")
    md()
    md(table(composition_by_stage(cells)))
    md()
    md("Dropout-robust marker statistic — fraction of cells with ≥ 1 UMI at stage 4 / stage 0, 95 % bootstrap over the 10 patients:")
    md()
    md(table(ratios))
    md()
    md("Earlier stages versus stage 0 (same statistic):")
    md()
    md(table(early))
    md()
    md("ABM live cells by local stage (voxel matrix ≥ 0.8 → stage 0 … < 0.2 → stage 4; overload runs 0.07–0.12 MPa, 2 years):")
    md()
    md(table(abm))
    md()
    sen_ratio1 = abm.loc[1, "senescent"] / abm.loc[0, "senescent"]
    md(f"ABM ratios: senescent stage 1 / 0 = **{sen_ratio1:.1f}**, stage 4 / 0 = {abm.loc[4, 'senescent'] / abm.loc[0, 'senescent']:.1f}; "
       f"RUNX2-high stage 0 = {abm.loc[0, 'runx2_high']:.3f} → stage 4 = {abm.loc[4, 'runx2_high']:.2f}; SOX9-high (not RUNX2-high) "
       f"at stage 4 = {1 - abm.loc[4, 'runx2_high']:.2f} vs SOX9 detected in {ratios.loc['SOX9', 'frac_stage4']:.2f} of cells in the data.")
    md()

    # ---------------------------------------------------------------- 6. conclusions
    md("## 6. What the data say about the model")
    md()
    md("* **Supported.** Medial-predominant loss follows from the measured in vivo medial force share without being fitted; "
       "a valgus load distribution reverses it. The direction of the cell-state changes agrees with the data: MMP13+ and p16+ cells increase in the most degraded "
       "cartilage (stage 4 / 0 intervals exclude 1); RUNX2+ cells change in the same direction (interval includes 1).")
    md("* **Not supported.** (i) Senescence and the SOX9 → RUNX2 switch occur far too early and too completely in the ABM: the data "
       "show p16, RUNX2 and MMP13 detection without a clear rise up to stage 3 and SOX9 retained in > 90 % of cells at stage 4. (ii) The tissue response is "
       "all-or-none (a sharp stress threshold), so the model predicts essentially no lateral loss where a small one is observed. "
       "(iii) Early-OA thickening (KL 2) is absent from the model.")
    md("* **Implication for stage 2.** Replace the instantaneous overload-driven senescence hazard by a cumulative-damage hazard, "
       "allow graded SOX9/RUNX2 co-expression (lower cooperativity or a third, intermediate state), add matrix swelling, and calibrate "
       "against longitudinal OAI data (requires NDA access).")
    md()
    md("## 7. Assumptions (each one is a place where this analysis can be wrong)")
    md()
    md("1. Loads come from total knee replacements (no menisci, no cruciate ligaments) — native-knee load sharing differs.")
    md("2. The medial force share of the OAI knees is drawn from 8 OrthoLoad subjects; alignment of the OAI knees is not in the open data.")
    md("3. Menisci carry the same share of the load in both compartments (κ is common to both plates).")
    md("4. KL0 knees are taken as the no-loss reference; cross-sectional differences are interpreted as loss.")
    md("5. \"Eroded depth\" (voxel matrix < 0.3) is the model counterpart of central thickness loss.")
    md("6. Ji et al.'s stage is matched to the ABM's local matrix content bins; marker detection is binary (≥ 1 UMI).")
    md("7. Body weight does not enter stage 1: a common load level is calibrated, so BMI effects are not tested here (stage 2).")
    md()
    md(f"_Runtime {time.perf_counter() - t0:.0f} s._")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
