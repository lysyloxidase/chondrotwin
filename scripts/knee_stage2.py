#!/usr/bin/env python
"""Stage 2: revised cell-state rules, calibrated on GSE104782 patients OA1-5, tested on OA6-10, on the OAIZIB-CM
tissue test and on the independent, pre-registered GSE152805 test.

Usage:  python scripts/fetch_data.py                       # once
        python scripts/knee_stage2_grid.py && python scripts/knee_stage2_grid.py --refine   # ~20 min
        python scripts/knee_stage2.py [--out docs/knee_stage2.md]                          # ~10 min first time
"""
import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

from chondrotwin import datasets
from chondrotwin.abm import Rates
from chondrotwin.knee import calibrate as C
from chondrotwin.knee import loads as L
from chondrotwin.knee.analysis import mixture_test, observed_losses
from chondrotwin.knee.erosion import curve, dose_response
from chondrotwin.knee.geometry import tibial_geometry
from chondrotwin.knee.independent import agreement, gse152805_ratios, model_ratios
from chondrotwin.knee.report import table

ROOT = Path(__file__).resolve().parents[1]
DERIVED = datasets.data_dir().parent / "derived"
H_MED, H_LAT, YEAR = 2.2, 2.6, 5
STAGE1 = dict(damage_D50=0.0, c_over_max=0.9, k_cat=0.0, baseline_runx2=0.0)
out = []


def md(s=""):
    print(s)
    out.append(s)


def stage_table(tables: pd.DataFrame, p: dict) -> pd.DataFrame:
    """Stage table pooled over seeds (cell-number weighted means; n summed)."""
    m = np.ones(len(tables), bool)
    for k, v in p.items():
        m &= np.isclose(tables[k].fillna(0.0), v)
    d = tables[m]
    if d.empty:
        raise ValueError(f"no stage table for {p}")
    cols = ["runx2_high", "senescent", "clustered", "catabolic", "mean_S", "mean_R"]
    w = d["n"].fillna(0.0)
    pooled = d[cols].mul(w, axis=0).groupby(d["stage"]).sum().div(w.groupby(d["stage"]).sum(), axis=0)
    pooled["n"] = w.groupby(d["stage"]).sum().astype(int)
    return pooled.reindex(range(5))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "knee_stage2.md"))
    a = ap.parse_args()
    t0 = time.perf_counter()
    g1 = pd.read_csv(DERIVED / "stage2_grid.csv").assign(baseline_runx2=0.0, round=1)
    g2 = pd.read_csv(DERIVED / "stage2_grid_refine.csv").assign(round=2)
    grid = pd.concat([g1, g2], ignore_index=True)
    keys = ["damage_D50", "c_over_max", "k_cat", "baseline_runx2"]
    sel = pd.read_csv(DERIVED / "stage2_selection.csv")
    tables = pd.read_csv(DERIVED / "stage2_selection_tables.csv")
    summ = sel.groupby(keys)[["loss_cal", "loss_val"]].agg(["mean", "std"]).sort_values(("loss_cal", "mean"))
    P2 = dict(zip(keys, map(float, summ.index[0])))
    best = summ.iloc[0]
    base = summ.loc[tuple(STAGE1[k] for k in keys)]

    md("# Knee cartilage simulation from open data — stage 2 results")
    md()
    md("_Generated by `scripts/knee_stage2.py`; do not edit by hand. Stage 1: `docs/knee_open_data.md`; "
       "pre-registration of the independent test: `docs/preregistration_gse152805.md`._")
    md()
    md("## 1. Revised rules and calibration (GSE104782, patients OA1–OA5)")
    md()
    md("Each revision answers a stage-1 falsification; with default values the ABM is the 0.2–0.4 model "
       "(bit-identical published time courses, `tests/test_abm.py`):")
    md()
    md("* `damage_D50` — senescence hazard scaled by accumulated overload D / (D + D50) (cumulative damage);")
    md("* `c_over_max` — largest catabolic bias that strain alone can produce (below the saddle-node 0.51, overload "
       "alone cannot flip a SOX9-high cell; inflammation is then required);")
    md("* `k_cat` — switch-independent catabolism (NF-κB / HIF-2α → MMP13): degradation ∝ (R + k_cat · overload);")
    md("* `baseline_runx2` — fraction of RUNX2-high cells at the start (stage-0 cartilage of OA knees has RUNX2+ cells).")
    md()
    md(f"Grid search with seed 1 ({len(grid)} parameter sets in two rounds; the second round was added because the first put "
       f"`c_over_max` on the grid boundary and left the stage-0 RUNX2+ cells unexplained). Selection by the calibration "
       f"loss only. Top 8:")
    md()
    top = grid.sort_values("loss_cal").head(8).set_index("round")[keys + ["loss_cal", "loss_val"]]
    md(table(top, "{:.3g}"))
    md()
    md("The 5 best sets were re-run with seeds 2 and 3 and the set with the lowest *mean* calibration loss was selected "
       "(`scripts/knee_stage2_select.py`); the stage-1 model was re-run with the same seeds:")
    md()
    md("| model | loss, calibration patients OA1–5 | loss, validation patients OA6–10 |")
    md("|---|---|---|")
    md(f"| stage 1 (0.4.0) | {base[('loss_cal', 'mean')]:.0f} ± {base[('loss_cal', 'std')]:.0f} | "
       f"{base[('loss_val', 'mean')]:.0f} ± {base[('loss_val', 'std')]:.0f} |")
    md(f"| stage 2 (selected) | {best[('loss_cal', 'mean')]:.0f} ± {best[('loss_cal', 'std')]:.0f} | "
       f"**{best[('loss_val', 'mean')]:.0f} ± {best[('loss_val', 'std')]:.0f}** |")
    md()
    md("(mean ± SD over 3 seeds)")
    md()
    md(f"Selected: D50 = {P2['damage_D50']:g} overload-days, c_over_max = {P2['c_over_max']:g}, k_cat = {P2['k_cat']:g}, "
       f"baseline RUNX2-high fraction = {P2['baseline_runx2']:g}.")
    md()

    cells = C.ji_cell_table()
    val = C.data_targets(cells, C.VAL_PATIENTS)
    st1, st2 = stage_table(tables, STAGE1), stage_table(tables, P2)
    lr1, lr2 = C.model_log_ratios(st1), C.model_log_ratios(st2)
    rows = []
    for gname in ("CDKN2A", "RUNX2", "MMP13", "SOX9"):
        for s in (1, 2, 3, 4):
            rows.append({"marker / stage": f"{gname} {s}", "data (OA6–10)": val["log_ratio"].loc[s, gname],
                         "± sd": float(np.sqrt(val["var"].loc[s, gname])), "stage-1 model": lr1.loc[s, gname],
                         "stage-2 model": lr2.loc[s, gname]})
    md("Validation patients: log-ratio stage s / stage 0 (data sd from a patient bootstrap, floored at 0.14):")
    md()
    md(table(pd.DataFrame(rows).set_index("marker / stage"), "{:.2f}"))
    md()
    md("ABM stage tables (live cells; stage from local matrix content):")
    md()
    cols = ["runx2_high", "senescent", "catabolic", "mean_S", "n"]
    md(table(pd.concat({"stage 1 model": st1[cols], "stage 2 model": st2[cols]}, axis=1)
             .set_axis([f"{a} {b}" for a, b in pd.concat({"s1": st1[cols], "s2": st2[cols]}, axis=1).columns], axis=1)))
    md()

    # ---------------------------------------------------------------- tissue
    geo = tibial_geometry()
    sig = np.round(np.arange(0.06, 0.3001, 0.01), 3)
    cache = DERIVED / "abm_dose_response_stage2.csv"
    if cache.exists():
        dose2 = pd.read_csv(cache)
    else:
        r2 = Rates.stage2(P2["damage_D50"], P2["c_over_max"], P2["k_cat"])
        dose2 = pd.concat([dose_response(sig, h, years=YEAR, seeds=(0, 1), rates=r2,
                                         initial_hypertrophic_fraction=P2["baseline_runx2"]) for h in (H_MED, H_LAT)],
                          ignore_index=True)
        dose2.to_csv(cache, index=False)
    dose1 = pd.read_csv(DERIVED / "abm_dose_response.csv")
    loads = L.load_all()
    l_cal = L.calibrate_condylar_distance(loads)
    mr = L.summary(loads, l_cal).medial_ratio.values
    md("## 2. Tissue test (OAIZIB-CM; same protocol as stage 1)")
    md()
    s2m, e2m = curve(dose2, H_MED, YEAR)
    md("Stage-2 dose–response (medial plate, 5 years): " + ", ".join(f"{e:.2f} mm at {s:.2f}" for s, e in zip(s2m, e2m)
                                                                  if round(s * 1000) % 20 == 0) + " MPa.")
    md()
    obs = observed_losses(geo).set_index(["split", "compartment"])
    rows = []
    for name, dose in (("stage 1", dose1), ("stage 2", dose2)):
        for yr in (2, YEAR):
            r = mixture_test(geo, mr, dose, H_MED, H_LAT, yr)
            if not r.get("calibrated"):
                rows.append({"model": name, "ABM years": yr, "load scale (MPa)": float("nan"),
                             "predicted lateral loss (mm)": float("nan"), "note": "no erosion at any stress yet"})
                continue
            rows.append({"model": name, "ABM years": yr, "load scale (MPa)": r["load_scale_MPa"],
                         "predicted lateral loss (mm)": r["predicted_mean_lateral_loss_mm"], "note": ""})
    tt = pd.DataFrame(rows).set_index("model")
    md(table(tt))
    md()
    for split in ("train", "test"):
        md(f"Observed lateral loss ({split}): {obs.loc[(split, 'lateral'), 'loss_mm']:.3f} ± {obs.loc[(split, 'lateral'), 'se_mm']:.3f} mm.")
        md()

    # ---------------------------------------------------------------- independent test
    md("## 3. Independent, pre-registered test (GSE152805: damaged medial vs minimally damaged lateral tibia, 3 patients)")
    md()
    data = gse152805_ratios()
    md("Samples after the pre-registered QC (≥ 500 genes, ≤ 20 % mitochondrial UMIs):")
    md()
    md(table(data.attrs["samples"].set_index(["patient"]), "{:.4f}"))
    md()
    md("Per-patient MT / oLT ratios:")
    md()
    md(table(data))
    md()
    agr = pd.concat({"stage 1": agreement(data, model_ratios(st1)), "stage 2": agreement(data, model_ratios(st2))})
    md(table(agr.reset_index().set_index("level_0")))
    md()
    n1, n2 = int(agr.loc["stage 1", "agrees"].sum()), int(agr.loc["stage 2", "agrees"].sum())
    md(f"Markers within the per-patient range (pre-registered criterion): **stage 1: {n1} / 4, stage 2: {n2} / 4.**")
    md()
    md("Exploratory, *not* pre-registered: direction of change (damaged vs intact) in model and data "
       "(geometric mean of the three patients):")
    md()
    dirs = []
    for mk in agr.loc["stage 1"].index:
        dg = float(np.sign(np.log(agr.loc[("stage 1", mk), "data_geomean"])))
        dirs.append({"marker": mk, "data": "up" if dg > 0 else "down",
                     "stage 1": "up" if agr.loc[("stage 1", mk), "model"] > 1 else "down",
                     "stage 2": "up" if agr.loc[("stage 2", mk), "model"] > 1 else "down"})
    md(table(pd.DataFrame(dirs).set_index("marker")))
    md()
    md("Infinite model ratios: the model's intact tissue contains no RUNX2-high cells at all, whereas 1–5 % of cells "
       "in the minimally damaged lateral plateau have RUNX2 transcripts.")
    md()

    # ---------------------------------------------------------------- conclusions
    v_s1 = lr1.loc[1, "CDKN2A"]; v_s2 = lr2.loc[1, "CDKN2A"]; v_d = val["log_ratio"].loc[1, "CDKN2A"]
    md("## 4. Conclusions")
    md()
    md(f"* **Cell states, held-out patients: improved.** Validation loss {base[('loss_val', 'mean')]:.0f} → "
       f"{best[('loss_val', 'mean')]:.0f}. Two of the revisions were selected: strain alone can no longer flip a SOX9-high "
       f"cell (c_over_max = {P2['c_over_max']:g} < 0.51) and catabolism partly bypasses the switch (k_cat = {P2['k_cat']:g}). "
       f"Mean SOX9 activity in the most degraded tissue is now {100 * st2.loc[4, 'mean_S'] / st2.loc[0, 'mean_S']:.0f} % "
       f"of intact tissue (stage-1 model {100 * st1.loc[4, 'mean_S'] / st1.loc[0, 'mean_S']:.0f} %; data, validation "
       f"patients, {100 * np.exp(val['log_ratio'].loc[4, 'SOX9']):.0f} %).")
    md(f"* **Senescence timing: not improved.** The cumulative-damage hazard was not selected (D50 = {P2['damage_D50']:g}). "
       f"Stage 1 vs 0 p16 log-ratio: data {v_d:+.2f}, stage-1 model {v_s1:+.2f}, stage-2 model {v_s2:+.2f}. In the model, "
       f"degrading tissue stays overloaded long enough to reach the damage thresholds tested (D50 up to 1000 "
       f"overload-days); senescence then saturates at 100 %, which also fails the independent test (model {agr.loc[('stage 2', 'CDKN2A_detected'), 'model']:.1f}× vs "
       f"data {agr.loc[('stage 2', 'CDKN2A_detected'), 'data_min']:.1f}–{agr.loc[('stage 2', 'CDKN2A_detected'), 'data_max']:.1f}×).")
    md(f"* **Independent pre-registered test: {n2} / 4 (stage 2) vs {n1} / 4 (stage 1).** The direction of change is right "
       f"for every marker in both models; magnitudes fail because intact model tissue has no RUNX2+ cells and senescence "
       f"saturates.")
    md("* **Tissue: unchanged.** The lateral plate is still predicted not to erode where a small loss is observed. The "
       "stage-2 model has a latent period (no erosion at any stress within 2 simulated years) followed by rapid, "
       "threshold-like erosion, so its tissue prediction now depends on the unknown time scale.")
    md("* **Next (stage 3).** A RUNX2+ subpopulation in intact cartilage (cell-to-cell heterogeneity of the switch rather "
       "than a uniform initial state), senescence that is not an absorbing fate of every overloaded cell (e.g. clearance "
       "or a damage-independent cap), and longitudinal OAI data to fix the time scale.")
    md()
    md(f"_Runtime {time.perf_counter() - t0:.0f} s._")
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
