#!/usr/bin/env python
"""Stage 3: cell-to-cell heterogeneity (switch bias, senescence competence); calibration on GSE104782 OA1-5,
validation on OA6-10, the previously seen GSE152805, the OAIZIB-CM tissue test and the pre-registered bulk test
(GSE57218 primary, GSE114007 secondary).

Usage:  python scripts/knee_stage3_calibrate.py      # once, ~15 min; freezes the parameters
        python scripts/knee_stage3.py [--out docs/knee_stage3.md]     # ~10 min the first time (dose-response)
"""
import argparse
import hashlib
import json
import re
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

from chondrotwin import datasets
from chondrotwin.abm import Rates
from chondrotwin.knee import calibrate as C
from chondrotwin.knee import independent2 as B
from chondrotwin.knee import loads as L
from chondrotwin.knee.analysis import mixture_test, observed_losses
from chondrotwin.knee.erosion import curve, dose_response
from chondrotwin.knee.geometry import tibial_geometry
from chondrotwin.knee.independent import agreement, gse152805_ratios, model_ratios
from chondrotwin.knee.report import table

ROOT = Path(__file__).resolve().parents[1]
DERIVED = datasets.data_dir().parent / "derived"
H_MED, H_LAT, YEAR = 2.2, 2.6, 5
KEYS = ["damage_D50", "c_over_max", "k_cat", "switch_bias_sd", "senescence_competent_fraction", "baseline_runx2"]
STAGE1 = dict(damage_D50=0.0, c_over_max=0.9, k_cat=0.0, switch_bias_sd=0.0, senescence_competent_fraction=1.0, baseline_runx2=0.0)
STAGE2 = dict(STAGE1, c_over_max=0.15, k_cat=0.5)
out = []


def md(s=""):
    print(s)
    out.append(s)


def pooled(tables: pd.DataFrame, p: dict) -> pd.DataFrame:
    m = np.ones(len(tables), bool)
    for k, v in p.items():
        m &= np.isclose(tables[k].astype(float), v)
    d = tables[m]
    cols = ["runx2_high", "senescent", "clustered", "catabolic", "mean_S", "mean_R", "mean_cat"]
    w = d["n"].fillna(0.0)
    res = d[cols].mul(w, axis=0).groupby(d["stage"]).sum().div(w.groupby(d["stage"]).sum(), axis=0)
    res["n"] = w.groupby(d["stage"]).sum().astype(int)
    return res.reindex(range(5))


def check_registration():
    pre = (ROOT / "docs" / "preregistration_stage3.md").read_text(encoding="utf-8")
    reg = re.search(r"independent2\.py` at registration: `([0-9a-f]{64})`", pre).group(1)
    now = hashlib.sha256((ROOT / "chondrotwin" / "knee" / "independent2.py").read_bytes()).hexdigest()
    frz = re.search(r"stage3_frozen_parameters\.json`: `([0-9a-f]{64})`", pre).group(1)
    frz_now = hashlib.sha256((ROOT / "docs" / "stage3_frozen_parameters.json").read_bytes()).hexdigest()
    return reg == now, frz == frz_now


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "knee_stage3.md"))
    a = ap.parse_args()
    t0 = time.perf_counter()
    proto_ok, frozen_ok = check_registration()
    P3 = json.loads((ROOT / "docs" / "stage3_frozen_parameters.json").read_text())["stage3_parameters"]
    sel = pd.read_csv(DERIVED / "stage3_selection.csv")
    tabs = pd.read_csv(DERIVED / "stage3_selection_tables.csv")
    grid = pd.read_csv(DERIVED / "stage3_grid.csv")
    summ = sel.groupby(KEYS)[["loss_cal", "loss_val"]].agg(["mean", "std"]).sort_values(("loss_cal", "mean"))
    same = all(np.isclose(P3[k], STAGE2[k]) for k in KEYS)
    het = [i for i in summ.index if i[KEYS.index("switch_bias_sd")] > 0 or i[KEYS.index("senescence_competent_fraction")] < 1]
    EXPL = dict(zip(KEYS, map(float, het[0])))
    PARAMS = {"stage 1": STAGE1, "stage 2 = 3": P3, "heterogeneous (exploratory)": EXPL} if same else         {"stage 1": STAGE1, "stage 2": STAGE2, "stage 3": P3, "heterogeneous (exploratory)": EXPL}
    st = {name: pooled(tabs, p) for name, p in PARAMS.items()}

    md("# Knee cartilage simulation from open data — stage 3 results")
    md()
    md("_Generated by `scripts/knee_stage3.py`; do not edit by hand. Earlier stages: `docs/knee_open_data.md`, "
       "`docs/knee_stage2.md`; pre-registration: `docs/preregistration_stage3.md`._")
    md()
    md(f"Registration check: protocol file unchanged since registration — **{proto_ok}**; frozen parameters unchanged "
       f"— **{frozen_ok}**.")
    md()
    md("## 1. Revisions and calibration (GSE104782, patients OA1–OA5)")
    md()
    md("Both revisions add cell-to-cell heterogeneity, each answering a stage-2 failure; with default values the model "
       "is the 0.2–0.5 model (bit-identical published time courses):")
    md()
    md("* `switch_bias_sd` — fixed per-cell offset of the switch bias, δ ~ N(0, sd): some cells are RUNX2-high even in "
       "intact cartilage (stage 2 had none; the data have 1–11 % RUNX2+ cells there);")
    md("* `senescence_competent_fraction` — only this fraction of cells can become senescent, so senescence no longer "
       "saturates at 100 % (stage 2: 100 %; data: p16+ cells rise about 2–3-fold).")
    md()
    md(f"Grid of {len(grid)} sets (seed 1) over these two plus `c_over_max` and `k_cat`; the 5 best re-run with seeds 2–3 "
       f"together with the stage-1 and stage-2 models; selected by mean calibration loss and frozen before the bulk "
       f"test data were read.")
    md()
    rows = []
    for name, p in PARAMS.items():
        r = summ.loc[tuple(float(p[k]) for k in KEYS)]
        rows.append({"model": name, "loss OA1–5 (calibration)": f"{r[('loss_cal', 'mean')]:.0f} ± {r[('loss_cal', 'std')]:.0f}",
                     "loss OA6–10 (validation)": f"{r[('loss_val', 'mean')]:.0f} ± {r[('loss_val', 'std')]:.0f}"})
    md(table(pd.DataFrame(rows).set_index("model")))
    md()
    md("Selected stage-3 parameters: " + ", ".join(f"{k} = {P3[k]:g}" for k in KEYS) + ".")
    md()
    if same:
        md("**The selected stage-3 parameters are the stage-2 parameters: neither heterogeneity mechanism improved the "
           "calibration loss** (best heterogeneous set: " + ", ".join(f"{k} = {EXPL[k]:g}" for k in KEYS) + "). The "
           "stage-3 hypotheses are therefore not supported by the calibration data. That set is carried along below "
           "only as an *exploratory* comparison; it was not selected and does not enter any pre-registered criterion.")
        md()
    cells = C.ji_cell_table()
    val = C.data_targets(cells, C.VAL_PATIENTS)
    lrs = {n: C.model_log_ratios(t) for n, t in st.items()}
    rows = []
    for gname in ("CDKN2A", "RUNX2", "MMP13", "SOX9"):
        for s in (1, 2, 3, 4):
            rows.append({"marker / stage": f"{gname} {s}", "data OA6–10": val["log_ratio"].loc[s, gname],
                         "± sd": float(np.sqrt(val["var"].loc[s, gname])),
                         **{n: lrs[n].loc[s, gname] for n in lrs}})
    md("Validation patients, log-ratio stage s / stage 0:")
    md()
    md(table(pd.DataFrame(rows).set_index("marker / stage"), "{:.2f}"))
    md()
    cols = ["runx2_high", "senescent", "mean_S", "mean_R", "n"]
    md("Live cells by local stage, selected model and the exploratory heterogeneous set:")
    md()
    sel_name = "stage 2 = 3" if same else "stage 3"
    md(table(pd.concat({sel_name: st[sel_name][cols], "het.": st["heterogeneous (exploratory)"][cols]}, axis=1)
             .set_axis([f"{a} {b}" for a, b in pd.concat({sel_name: st[sel_name][cols], "het.": st["heterogeneous (exploratory)"][cols]}, axis=1).columns], axis=1)))
    md()

    # ---------------------------------------------------------------- tissue
    geo = tibial_geometry()
    cache = DERIVED / "abm_dose_response_stage3.csv"
    if same:
        dose3 = None
    elif cache.exists():
        dose3 = pd.read_csv(cache)
    else:
        r3 = Rates(**{k: P3[k] for k in KEYS if k != "baseline_runx2"})
        sig = np.round(np.arange(0.06, 0.3001, 0.01), 3)
        dose3 = pd.concat([dose_response(sig, h, years=YEAR, seeds=(0, 1), rates=r3,
                                         initial_hypertrophic_fraction=P3["baseline_runx2"]) for h in (H_MED, H_LAT)],
                          ignore_index=True)
        dose3.to_csv(cache, index=False)
    doses = {"stage 1": pd.read_csv(DERIVED / "abm_dose_response.csv"),
             "stage 2": pd.read_csv(DERIVED / "abm_dose_response_stage2.csv")}
    if not same:
        doses["stage 3"] = dose3
    loads = L.load_all()
    mr = L.summary(loads, L.calibrate_condylar_distance(loads)).medial_ratio.values
    md("## 2. Tissue test (OAIZIB-CM; protocol of stage 1)")
    md()
    if same:
        md("The selected stage-3 model is the stage-2 model, so the tissue results of stage 2 apply unchanged:")
        md()
    else:
        s3, e3 = curve(dose3, H_MED, YEAR)
        md("Stage-3 dose–response (medial plate, 5 years): " + ", ".join(f"{e:.2f} mm at {s:.2f}" for s, e in zip(s3, e3)
                                                                      if round(s * 1000) % 20 == 0) + " MPa.")
        md()
    rows = []
    for name, dose in doses.items():
        for yr in (2, YEAR):
            r = mixture_test(geo, mr, dose, H_MED, H_LAT, yr)
            ok = r.get("calibrated", False)
            rows.append({"model": name, "ABM years": yr, "load scale (MPa)": r["load_scale_MPa"] if ok else float("nan"),
                         "predicted lateral loss (mm)": r["predicted_mean_lateral_loss_mm"] if ok else float("nan"),
                         "note": "" if ok else "no erosion at any stress yet"})
    md(table(pd.DataFrame(rows).set_index("model")))
    md()
    obs = observed_losses(geo).set_index(["split", "compartment"])
    md(f"Observed lateral loss: train {obs.loc[('train', 'lateral'), 'loss_mm']:.3f} ± {obs.loc[('train', 'lateral'), 'se_mm']:.3f} mm, "
       f"test {obs.loc[('test', 'lateral'), 'loss_mm']:.3f} ± {obs.loc[('test', 'lateral'), 'se_mm']:.3f} mm.")
    md()

    # ---------------------------------------------------------------- GSE152805 (previously seen)
    md("## 3. GSE152805 — previously seen, not independent for stage 3")
    md()
    md("The stage-3 revisions were motivated by this test's stage-2 failures, so its result for stage 3 is a consistency "
       "check, not an out-of-sample test.")
    md()
    d152 = gse152805_ratios()
    agr = pd.concat({n: agreement(d152, model_ratios(t)) for n, t in st.items()})
    md(table(agr.reset_index().set_index("level_0")[["marker", "data_min", "data_max", "model", "agrees"]]))
    md()
    n152 = {n: int(agr.loc[n, "agrees"].sum()) for n in st}
    md("Within the per-patient range: " + ", ".join(f"{n}: {v} / 4" for n, v in n152.items()) + ".")
    md()

    # ---------------------------------------------------------------- bulk independent test
    md("## 4. Pre-registered independent test — bulk cartilage transcriptomes")
    md()
    pairs = B.gse57218_pairs()
    md(f"GSE57218 (RAAK): {len(pairs)} joint-matched pairs OA − preserved; probes " +
       ", ".join(f"{g}: {p}" for g, p in pairs.attrs["probes"].items()) + ".")
    md()
    models = {n: B.model_log2(t) for n, t in st.items()}
    rows = []
    for gname in B.GENES:
        m, lo, hi, n = B.t_interval(pairs[gname].to_numpy())
        r = {"gene": gname, "data mean log2": m, "95 % CI low": lo, "95 % CI high": hi, "pairs": n}
        for name, mv in models.items():
            r[f"{name} log2"] = mv[gname]
            r[f"{name} C1"] = B.criterion_c1(m, lo, hi, mv[gname])
        rows.append(r)
    prim = pd.DataFrame(rows).set_index("gene")
    md(table(prim, "{:.2f}"))
    md()
    c1_prim = {n: int(prim[f"{n} C1"].sum()) for n in models}
    md("**Primary (GSE57218, C1 direction):** " + ", ".join(f"{n} {v} / 4" for n, v in c1_prim.items()) + ".")
    md()
    sec = B.gse114007_log2_ratios()
    rows = []
    for gname in B.GENES:
        e, lo, hi = sec.loc[gname, "log2_ratio"], sec.loc[gname, "ci_low"], sec.loc[gname, "ci_high"]
        r = {"gene": gname, "data log2 OA/normal": e, "95 % CI low": lo, "95 % CI high": hi}
        for name, mv in models.items():
            r[f"{name} C1"] = B.criterion_c1(e, lo, hi, mv[gname])
            r[f"{name} C2"] = B.criterion_c2(lo, hi, mv[gname])
        rows.append(r)
    secd = pd.DataFrame(rows).set_index("gene")
    md(f"GSE114007: {int(sec['n_oa'].iloc[0])} OA vs {int(sec['n_normal'].iloc[0])} normal samples (RNA-seq).")
    md()
    md(table(secd, "{:.2f}"))
    md()
    c1_sec = {n: int(secd[f"{n} C1"].sum()) for n in models}
    c2_sec = {n: int(secd[f"{n} C2"].sum()) for n in models}
    md("**Secondary (GSE114007):** C1 " + ", ".join(f"{n} {v} / 4" for n, v in c1_sec.items()) +
       "; C2 " + ", ".join(f"{n} {v} / 4" for n, v in c2_sec.items()) + ".")
    md()

    # ---------------------------------------------------------------- deviations / diagnostics (post hoc)
    md("## 5. Deviations and diagnostics (post hoc — not part of the registered result)")
    md()
    n_raw = B._read_counts("GSE114007_normal_normalized.counts.txt.gz")
    o_raw = B._read_counts("GSE114007_OA_normalized.counts.txt.gz")
    neg = {g: (int((n_raw.loc[g] < 0).sum()), int((o_raw.loc[g] < 0).sum())) for g in B.GENES}
    md(f"* **GSE114007 is not analysable as registered.** The files named \"normalized counts\" contain negative values "
       f"({float((n_raw < 0).to_numpy().mean() * 100):.1f} % of all entries in the normal file, "
       f"{float((o_raw < 0).to_numpy().mean() * 100):.1f} % in the OA file; negative entries normal/OA: "
       + ", ".join(f"{g} {a}/{b}" for g, (a, b) in neg.items()) +
       "), i.e. they are batch-corrected values, not counts. Ratios of mean CPM are then undefined for MMP13 and CDKN2A "
       "(NaN intervals) and not meaningful for the others. The registered secondary result is therefore declared "
       "invalid. A valid analysis needs `GSE114007_raw_counts.xlsx`, which was not downloaded.")
    vals = {}
    with __import__("gzip").open(datasets.require("gse57218", "GSE57218_series_matrix.txt.gz"), "rt") as fh:
        for line in fh:
            if line.startswith("!series_matrix_table_begin"):
                next(fh)
                break
        for line in fh:
            if line.startswith("!series_matrix_table_end"):
                break
            v = line.rstrip().split("	")
            vals[v[0].strip('"')] = np.nanmean([float(x) for x in v[1:] if x not in ("", "null")])
    allp = pd.Series(vals)
    pct = {g: float((allp < allp[pr]).mean() * 100) for g, pr in pairs.attrs["probes"].items()}
    md("* **GSE57218 probe intensity** (percentile of the probe's mean among all probes): " +
       ", ".join(f"{g} {v:.0f}th" for g, v in pct.items()) +
       ". The CDKN2A probe is close to the array background, so its \"no change\" is weak evidence; the narrow "
       "interval reflects low signal rather than precise measurement.")
    md("* Direction of the within-joint MMP13 change: lower in OA-affected than in preserved cartilage of the same joint "
       "in GSE57218, while the model (any stage) predicts higher catabolic drive in damaged tissue. Whether lesioned "
       "end-stage cartilage should be compared with the model's \"damaged\" tissue is itself an assumption of the "
       "protocol.")
    md()

    # ---------------------------------------------------------------- summary
    md("## 6. Summary")
    md()
    rows = []
    for name in st:
        r = summ.loc[tuple(float(PARAMS[name][k]) for k in KEYS)]
        rows.append({"model": name, "loss OA6–10": f"{r[('loss_val', 'mean')]:.0f}",
                     "GSE152805 (seen)": f"{n152[name]} / 4", "GSE57218 C1": f"{c1_prim[name]} / 4",
                     "GSE114007 C1": f"{c1_sec[name]} / 4", "GSE114007 C2": f"{c2_sec[name]} / 4"})
    md(table(pd.DataFrame(rows).set_index("model")))
    md()
    md("(GSE114007 columns: registered result, declared invalid in section 5.)")
    md()
    md("## 7. Conclusions")
    md()
    md("* **The stage-3 hypotheses were not supported.** Neither heterogeneity of the switch nor limited senescence "
       "competence improved the calibration on GSE104782, so the frozen stage-3 model is the stage-2 model; the best "
       "heterogeneous set also does worse on the validation patients and on every external dataset (exploratory).")
    md(f"* **Pre-registered primary test (GSE57218, 33 joint-matched pairs): stage 2 = 3 {c1_prim[sel_name]} / 4, stage 1 "
       f"{c1_prim['stage 1']} / 4.** The selected model is consistent with no material within-joint change of SOX9 "
       "and RUNX2, and it fails for MMP13 (data lower in OA-affected tissue, model higher) and for CDKN2A (data flat but "
       "near background; model strongly higher).")
    md("* **Overall, across stages:** the revisions kept so far (stage 2) improved the fit to held-out patients, to SOX9 "
       "in both external datasets and to RUNX2 in GSE57218 (not in GSE152805, where intact model tissue still has no "
       "RUNX2+ cells). None fixed senescence — the model's p16 rise starts earlier and saturates higher than in the "
       "validation patients and the external data — or catabolism in end-stage lesions. These are the two places where "
       "the model's logic, not its parameters, is most likely wrong.")
    md("* **What would change the picture:** longitudinal OAI data (time scale, tissue), GSE114007 raw counts (a valid "
       "secondary test), and a senescence readout better than one transcript (e.g. a multi-gene SASP / senescence score).")
    md()
    md(f"_Runtime {time.perf_counter() - t0:.0f} s._")
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
