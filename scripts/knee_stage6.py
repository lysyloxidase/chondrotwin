#!/usr/bin/env python
"""Stage 6: identifiability, prediction uncertainty and robustness of the selected (stage-2) model, and one scorecard of
every test from stages 1-5 recomputed from the data (no numbers copied by hand).

Usage:  python scripts/knee_stage6_run.py   # once (~15 min)
        python scripts/knee_stage6.py [--out docs/knee_stage6.md]
"""
import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

from chondrotwin import datasets
from chondrotwin.knee import calibrate as C
from chondrotwin.knee import independent as I1
from chondrotwin.knee import independent2 as I2
from chondrotwin.knee import independent3 as I3
from chondrotwin.knee import independent4 as I4
from chondrotwin.knee import loads as L
from chondrotwin.knee import uq
from chondrotwin.knee.analysis import mixture_test, observed_losses
from chondrotwin.knee.geometry import tibial_geometry
from chondrotwin.knee.report import table

ROOT = Path(__file__).resolve().parents[1]
DERIVED = datasets.data_dir().parent / "derived"
FULL1 = dict(damage_D50=0.0, c_over_max=0.9, k_cat=0.0, switch_bias_sd=0.0, senescence_competent_fraction=1.0,
             sen_overload_weight=1.0, senescent_death_rate=0.0, k_inf=0.0, sen_infl_gain=2.0, C_joint=0.0, baseline_runx2=0.0)
FULL2 = dict(FULL1, c_over_max=0.15, k_cat=0.5)
out = []


def md(s=""):
    print(s)
    out.append(s)


def pooled(tables, p):
    m = np.ones(len(tables), bool)
    for k, v in p.items():
        m &= np.isclose(tables[k].astype(float), v)
    d = tables[m]
    cols = ["runx2_high", "senescent", "clustered", "catabolic", "mean_S", "mean_R", "mean_cat"]
    w = d["n"].fillna(0.0)
    res = d[cols].mul(w, axis=0).groupby(d["stage"]).sum().div(w.groupby(d["stage"]).sum(), axis=0)
    res["n"] = w.groupby(d["stage"]).sum().astype(int)
    return res.reindex(range(5))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "knee_stage6.md"))
    a = ap.parse_args()
    t0 = time.perf_counter()
    prof = pd.read_csv(DERIVED / "stage6_profile.csv")
    mv = pd.read_csv(DERIVED / "stage6_multiverse.csv")

    md("# Knee cartilage simulation from open data — stage 6: how certain is the selected model?")
    md()
    md("_Generated by `scripts/knee_stage6.py`; do not edit by hand. No new data and no new hypothesis: stages 3–5 showed "
       "that further hypotheses tested on the same open data mostly fit data that had already been seen. This stage "
       "quantifies identifiability, prediction uncertainty and robustness of the model that survived (stage 2), and "
       "collects every test in one scorecard._")
    md()

    # ---------------------------------------------------------------- 1. identifiability
    g = prof.groupby(["c_over_max", "k_cat"])
    mean_cal = g["loss_cal"].mean().unstack()
    sd_cal = float(g["loss_cal"].std().mean())
    lmin = float(mean_cal.min().min())
    n_terms = 16
    thr = uq.chi2_threshold(n_terms, lmin)
    best = mean_cal.stack().idxmin()
    region = (mean_cal - lmin <= thr).stack()
    inside = region[region].index.tolist()
    co = sorted({c for c, _ in inside}); kc = sorted({k for _, k in inside})
    md("## 1. Identifiability of the two stage-2 parameters")
    md()
    md(f"Calibration loss (GSE104782 OA1–5, SenMayo readout; mean of 3 seeds; seed SD ≈ {sd_cal:.1f}) on a "
       f"{mean_cal.shape[0]} × {mean_cal.shape[1]} grid (rows `c_over_max`, columns `k_cat`):")
    md()
    shown = mean_cal.copy()
    shown.index = [f"{v:g}" for v in shown.index]
    shown.columns = [f"k_cat {v:g}" for v in shown.columns]
    shown.index.name = "c_over_max"
    md(table(shown, "{:.0f}"))
    md()
    md(f"Minimum {lmin:.0f} at c_over_max = {best[0]:g}, k_cat = {best[1]:g}. Approximate 95 % region: ΔL ≤ {thr:.1f} "
       f"(χ²₂ = 5.99 scaled by L_min / {n_terms - 2} = {lmin / (n_terms - 2):.1f} for misspecification). "
       f"Inside: c_over_max ∈ [{min(co):g}, {max(co):g}], k_cat ∈ [{min(kc):g}, {max(kc):g}] "
       f"({len(inside)} of {mean_cal.size} grid points).")
    md()
    edge_c = max(co) >= max(uq.PROFILE_GRID["c_over_max"]) or min(co) <= min(uq.PROFILE_GRID["c_over_max"])
    edge_k = max(kc) >= max(uq.PROFILE_GRID["k_cat"]) or min(kc) <= min(uq.PROFILE_GRID["k_cat"])
    md(f"* `c_over_max`: {'reaches the grid edge — only bounded on one side' if edge_c else 'bounded inside the grid'}; "
       f"the qualitative conclusion is whether it lies below the switch's saddle-node (0.51): "
       f"{'yes, everywhere in the region' if max(co) < 0.51 else 'not everywhere'}.")
    full_k = min(kc) <= min(uq.PROFILE_GRID["k_cat"]) and max(kc) >= max(uq.PROFILE_GRID["k_cat"])
    md(f"* `k_cat`: {'spans the whole tested range [0, 1] — **not identified** by these data' if full_k else ('reaches the grid edge — weakly identified' if edge_k else 'bounded inside the grid')}."
       + (" In particular k_cat = 0 is inside the region (with c_over_max ≤ "
          f"{max(c for c, kk in inside if kk == 0):g}), so the stage-2 statement that catabolism partly bypasses the switch "
          "is **not supported** as a separate finding; only the bound on c_over_max is." if full_k and any(kk == 0 for _, kk in inside) else ""))
    md()

    # ---------------------------------------------------------------- 2. prediction uncertainty
    pin = prof.set_index(["c_over_max", "k_cat"]).loc[inside].groupby(level=[0, 1]).mean()
    md("## 2. Prediction uncertainty inside the region")
    md()
    rows = []
    for col, label in (("sox9_retention_stage4", "mean SOX9 activity, stage 4 / stage 0"),
                       ("runx2_high_stage4", "RUNX2-high fraction, stage 4"),
                       ("senescent_stage4", "senescent fraction, stage 4"),
                       ("senescent_stage0", "senescent fraction, stage 0")):
        v = pin[col].dropna()
        rows.append({"prediction": label, "at the minimum": float(prof[(prof.c_over_max == best[0]) & (prof.k_cat == best[1])][col].mean()),
                     "range in region (low)": float(v.min()), "range in region (high)": float(v.max())})
    md(table(pd.DataFrame(rows).set_index("prediction"), "{:.2f}"))
    md()
    md("Senescence in the most degraded tissue is ~100 % everywhere in the region: the failure documented in stages 1–5 "
       "is structural, not a matter of parameter values.")
    md()

    # ---------------------------------------------------------------- 3. multiverse
    md("## 3. Robustness of the main conclusion (multiverse of analysis choices)")
    md()
    n = len(mv)
    k = int(mv["stage 2 better (val)"].sum())
    md(f"Claim tested: *the stage-2 model fits the held-out patients (GSE104782 OA6–10) better than the stage-1 model.* "
       f"Repeated in {n} universes = 4 simulation settings × 3 stage-bin definitions × 2 senescence readouts × "
       f"2 pseudo-counts (3 seeds each).")
    md()
    md(f"**Stage 2 better in {k} / {n} universes**; validation-loss ratio stage 1 / stage 2: median "
       f"{mv['val loss ratio stage1/stage2'].median():.1f}, range {mv['val loss ratio stage1/stage2'].min():.1f}–"
       f"{mv['val loss ratio stage1/stage2'].max():.1f}.")
    md()
    for factor in ("simulation", "stage bins", "senescence readout", "pseudo-count"):
        s = mv.groupby(factor).agg(universes=("stage 2 better (val)", "size"), stage2_better=("stage 2 better (val)", "sum"),
                                   min_ratio=("val loss ratio stage1/stage2", "min"),
                                   median_ratio=("val loss ratio stage1/stage2", "median"))
        s["stage2_better"] = s["stage2_better"].astype(int)
        md(table(s, "{:.2f}"))
        md()

    # ---------------------------------------------------------------- 4. scorecard
    md("## 4. Scorecard of all tests (recomputed)")
    md()
    tabs = pd.read_csv(DERIVED / "stage5_selection_tables.csv")
    st = {"stage 1": pooled(tabs, FULL1), "final (stage 2)": pooled(tabs, FULL2)}
    ji = C.ji_cell_table()
    rows = []
    for rname, pairs in (("CDKN2A", C.PAIRS), ("SenMayo", C.PAIRS4)):
        val = C.data_targets(ji, C.VAL_PATIENTS, pairs=pairs)
        r = {"test": f"GSE104782 held-out patients OA6–10 (loss, {rname} readout; lower is better)",
             "status": "split fixed before calibration"}
        for name, t in st.items():
            r[name] = f"{C.loss(C.model_log_ratios(t, pairs), val):.0f}"
        rows.append(r)
    d152 = I1.gse152805_ratios()
    r = {"test": "GSE152805 damaged vs intact, 3 patients (markers in per-patient range)", "status": "pre-registered (stage 2)"}
    for name, t in st.items():
        r[name] = f"{int(I1.agreement(d152, I1.model_ratios(t))['agrees'].sum())} / 4"
    rows.append(r)
    pairs57 = I2.gse57218_pairs()
    r = {"test": "GSE57218 within-joint pairs, n = 33 (C1)", "status": "pre-registered (stage 3)"}
    for name, t in st.items():
        m = I2.model_log2(t)
        r[name] = f"{sum(I2.criterion_c1(*I2.t_interval(pairs57[gn].to_numpy())[:3], m[gn]) for gn in I2.GENES)} / 4"
    rows.append(r)
    senm = I3.senmayo_genes()
    for label, loader, status in (("GSE117999 OA vs meniscus-tear knees (C1)", I3.gse117999, "pre-registered (stage 4), primary"),
                                  ("GSE169077 OA vs normal pools (C1)", I3.gse169077, "pre-registered (stage 4), secondary")):
        e, gr = loader()
        rd = I3.readouts(e, gr, senm)
        r = {"test": label, "status": status}
        for name, t in st.items():
            m = I3.model_log2(t)
            r[name] = f"{sum(I3.criterion_c1(*rd.loc[x, ['diff', 'ci_low', 'ci_high']].astype(float), m[x]) for x in rd.index)} / {len(rd)}"
        rows.append(r)
    geo = tibial_geometry()
    obs = observed_losses(geo).set_index(["split", "compartment"])
    loads = L.load_all()
    mr = L.summary(loads, L.calibrate_condylar_distance(loads)).medial_ratio.values
    r = {"test": f"OAIZIB-CM lateral tibial loss, KL4 (observed train {obs.loc[('train', 'lateral'), 'loss_mm']:.2f} ± "
                 f"{obs.loc[('train', 'lateral'), 'se_mm']:.2f} mm)", "status": "train calibration / test split seen in stage 1"}
    for name, f in (("stage 1", "abm_dose_response.csv"), ("final (stage 2)", "abm_dose_response_stage2.csv")):
        res = mixture_test(geo, mr, pd.read_csv(DERIVED / f), 2.2, 2.6, 5)
        r[name] = f"{res['predicted_mean_lateral_loss_mm']:.2f} mm"
    rows.append(r)
    comb = I4.combine(I4.contrasts())
    rows.append({"test": "Premise: OA synovium inflamed (GSE55235 + GSE55457)", "status": "pre-registered (stage 5); controls include trauma",
                 "stage 1": "—", "final (stage 2)": f"not supported ({comb.loc[('OA', 'inflammation score'), 'diff']:+.2f} "
                                                    f"[{comb.loc[('OA', 'inflammation score'), 'ci_low']:+.2f}, "
                                                    f"{comb.loc[('OA', 'inflammation score'), 'ci_high']:+.2f}])"})
    md(table(pd.DataFrame(rows).set_index("test")))
    md()

    # ---------------------------------------------------------------- 5. conclusions
    md("## 5. Conclusions")
    md()
    md(f"* **Identifiability:** the strain-only switch bias `c_over_max` is confined to [{min(co):g}, {max(co):g}] — below "
       f"the saddle-node in the whole region, so 'strain alone cannot flip the switch' is a robust conclusion. `k_cat` is "
       f"not identified (region spans [{min(kc):g}, {max(kc):g}], including 0): the stage-2 claim that catabolism partly "
       f"bypasses the switch is withdrawn as a separate finding.")
    md(f"* **Robustness:** stage 2 beats stage 1 on held-out patients in {k} of {n} analysis universes "
       f"(median loss ratio {mv['val loss ratio stage1/stage2'].median():.1f}).")
    md("* **Structural failure confirmed:** near-complete senescence in degraded tissue holds across the whole parameter "
       "region; no parameter choice within this model structure can fix it.")
    md("* **For the paper:** the scorecard above is the honest summary — the revisions improve cell-state predictions on "
       "held-out and independent data, the tissue-level and senescence predictions do not improve, and the synovial "
       "hypothesis could not be supported with open data.")
    md()
    md(f"_Runtime {time.perf_counter() - t0:.0f} s._")
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
