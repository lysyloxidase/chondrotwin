#!/usr/bin/env python
"""Stage 5: joint-level (synovial) inflammation. Calibration on GSE104782 OA1-5 (within-joint) + GSE114007 raw counts
(between-joint); consistency with the previously seen bulk datasets; pre-registered premise test on synovium
(GSE55235 + GSE55457); tissue test.

Usage:  python scripts/knee_stage5_calibrate.py      # once; freezes the parameters
        python scripts/knee_stage5.py [--out docs/knee_stage5.md]
"""
import argparse
import hashlib
import json
import re
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

from chondrotwin import datasets
from chondrotwin.abm import Rates
from chondrotwin.knee import calibrate as C
from chondrotwin.knee import independent2 as I2
from chondrotwin.knee import independent3 as I3
from chondrotwin.knee import independent4 as I4
from chondrotwin.knee import loads as L
from chondrotwin.knee.analysis import mixture_test, observed_losses
from chondrotwin.knee.geometry import tibial_geometry
from chondrotwin.knee.report import table

ROOT = Path(__file__).resolve().parents[1]
DERIVED = datasets.data_dir().parent / "derived"
H_MED, H_LAT, YEAR = 2.2, 2.6, 5
STAGE1 = dict(damage_D50=0.0, c_over_max=0.9, k_cat=0.0, switch_bias_sd=0.0, senescence_competent_fraction=1.0,
              sen_overload_weight=1.0, senescent_death_rate=0.0, k_inf=0.0, sen_infl_gain=2.0, C_joint=0.0,
              baseline_runx2=0.0)
STAGE2 = dict(STAGE1, c_over_max=0.15, k_cat=0.5)
KEYS = list(STAGE1)
GENES = ("SOX9", "RUNX2", "MMP13", "CDKN2A")
COL = {"SOX9": "mean_S", "RUNX2": "mean_R", "MMP13": "mean_cat", "CDKN2A": "senescent"}
out = []


def md(s=""):
    print(s)
    out.append(s)


def pooled(tables, p):
    m = np.ones(len(tables), bool)
    for k, v in p.items():
        m &= np.isclose(tables[k].astype(float), v)
    d = tables[m]
    cols = ["runx2_high", "senescent", "clustered", "catabolic", "mean_S", "mean_R", "mean_cat"]
    w = d["n"].fillna(0.0)
    res = d[cols].mul(w, axis=0).groupby(d["stage"]).sum().div(w.groupby(d["stage"]).sum(), axis=0)
    res["n"] = w.groupby(d["stage"]).sum().astype(int)
    return res.reindex(range(5))


def registration():
    pre = (ROOT / "docs" / "preregistration_stage5.md").read_text(encoding="utf-8")
    reg = re.search(r"independent4\.py` at registration: `([0-9a-f]{64})`", pre).group(1)
    frz = re.search(r"stage5_frozen_parameters\.json`: `([0-9a-f]{64})`", pre).group(1)
    h = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()   # noqa: E731
    return reg == h(ROOT / "chondrotwin" / "knee" / "independent4.py"), frz == h(ROOT / "docs" / "stage5_frozen_parameters.json")


def within_log2(st):
    m = I2.model_log2(st)
    return {g: m[g] for g in GENES}


def between_log2(sel_rows):
    oa = {c: sel_rows[f"oa_{c}"].mean() for c in COL.values()}
    nm = {c: sel_rows[f"normal_{c}"].mean() for c in COL.values()}
    return {g: float(np.log2(max(oa[COL[g]], 1e-6) / max(nm[COL[g]], 1e-6))) for g in GENES}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "knee_stage5.md"))
    a = ap.parse_args()
    t0 = time.perf_counter()
    proto_ok, frozen_ok = registration()
    P5 = json.loads((ROOT / "docs" / "stage5_frozen_parameters.json").read_text())["stage5_parameters"]
    sel = pd.read_csv(DERIVED / "stage5_selection.csv")
    tabs = pd.read_csv(DERIVED / "stage5_selection_tables.csv")
    summ = sel.groupby(KEYS)[["loss_cal", "loss_val", "loss_between", "loss_cells_val"]].agg(["mean", "std"]).sort_values(("loss_cal", "mean"))
    same = all(np.isclose(P5[k], STAGE2[k]) for k in KEYS)
    PARAMS = {"stage 1": STAGE1, "stage 2 (= 3 = 4)": STAGE2} if same else {"stage 1": STAGE1, "stage 2 (= 3 = 4)": STAGE2, "stage 5": P5}
    st = {n: pooled(tabs, p) for n, p in PARAMS.items()}

    def rows_of(p):
        m = np.ones(len(sel), bool)
        for k, v in p.items():
            m &= np.isclose(sel[k].astype(float), v)
        return sel[m]

    md("# Knee cartilage simulation from open data — stage 5 results")
    md()
    md("_Generated by `scripts/knee_stage5.py`; do not edit by hand. Pre-registration: `docs/preregistration_stage5.md`._")
    md()
    md(f"Registration check: protocol unchanged — **{proto_ok}**; frozen parameters unchanged — **{frozen_ok}**.")
    md()
    md("## 1. Hypothesis and revisions")
    md()
    md("Stage 4 found that catabolism (MMP13) is a joint-level OA feature (OA vs normal knees) rather than a lesion-level "
       "one, and that in the model the senescent cells' SASP was the only inflammatory source in cartilage. Stage 5 adds:")
    md()
    md("* `C_joint` — a joint-level cytokine background (synovial inflammation) throughout the cartilage of OA joints "
       "(0 in normal joints);")
    md("* `k_inf` — inflammation-driven catabolism, catabolic drive += k_inf · C/(K_C + C) (IL-1 / TNF → NF-κB → MMP13);")
    md("* `sen_infl_gain` — how strongly cytokines amplify the senescence hazard (2 before; 0 = not at all).")
    md()
    md("Calibration loss = within-joint stage ratios (GSE104782 OA1–5, SenMayo target) + between-joint OA/normal ratios "
       "(GSE114007 raw counts, RNA-seq). Both datasets were seen before, so everything in sections 2–3 is calibration or "
       "consistency, not an independent test.")
    md()
    md("## 2. Calibration")
    md()
    rows = []
    for n, p in PARAMS.items():
        r = summ.loc[tuple(float(p[k]) for k in KEYS)]
        rows.append({"model": n, "calibration (cells OA1–5 + between)": f"{r[('loss_cal', 'mean')]:.0f} ± {r[('loss_cal', 'std')]:.0f}",
                     "between-joint part": f"{r[('loss_between', 'mean')]:.0f}",
                     "cells, validation OA6–10": f"{r[('loss_cells_val', 'mean')]:.0f} ± {r[('loss_cells_val', 'std')]:.0f}"})
    md(table(pd.DataFrame(rows).set_index("model")))
    md()
    md("Selected (frozen): " + ", ".join(f"{k} = {P5[k]:g}" for k in ("C_joint", "k_inf", "sen_infl_gain", "c_over_max", "k_cat")) + ".")
    md()
    if same:
        md("**No stage-5 mechanism was selected; the model is the stage-2 model.**")
        md()
    btw = C.between_targets()
    rows = []
    for g in GENES:
        r = {"gene": g, "GSE114007 log2 OA/normal": btw.loc[g, "log_ratio"] / np.log(2),
             "± sd": float(np.sqrt(btw.loc[g, "var"]) / np.log(2))}
        for n, p in PARAMS.items():
            r[f"{n}"] = between_log2(rows_of(p))[g]
        rows.append(r)
    md("Between-joint fit (log2, OA joint vs normal joint; calibration target):")
    md()
    md(table(pd.DataFrame(rows).set_index("gene"), "{:.2f}"))
    md()

    # ---------------------------------------------------------------- 3. consistency with seen bulk data
    md("## 3. Within- vs between-joint contrasts against the previously seen bulk data (consistency, C1)")
    md()
    pairs = I2.gse57218_pairs()
    within_data = {g: I2.t_interval(pairs[g].to_numpy())[:3] for g in GENES}
    e169, g169 = I3.gse169077()
    r169 = I3.readouts(e169, g169, I3.senmayo_genes())
    e117, g117 = I3.gse117999()
    r117 = I3.readouts(e117, g117, I3.senmayo_genes())
    rows = []
    for n, p in PARAMS.items():
        w, b = within_log2(st[n]), between_log2(rows_of(p))
        r = {"model": n}
        r["GSE57218 within (C1)"] = sum(I3.criterion_c1(*within_data[g], w[g]) for g in GENES)
        r["GSE169077 between (C1)"] = sum(I3.criterion_c1(*r169.loc[g, ["diff", "ci_low", "ci_high"]].astype(float), b[g]) for g in GENES)
        r["GSE117999 OA vs meniscus tear (C1)"] = sum(I3.criterion_c1(*r117.loc[g, ["diff", "ci_low", "ci_high"]].astype(float), b[g]) for g in GENES)
        r["MMP13 within log2"] = w["MMP13"]
        r["MMP13 between log2"] = b["MMP13"]
        rows.append(r)
    md(table(pd.DataFrame(rows).set_index("model"), "{:.2f}"))
    md()
    md(f"Data: MMP13 within joint {within_data['MMP13'][0]:+.2f} (GSE57218), between joints "
       f"{r169.loc['MMP13', 'diff']:+.2f} (GSE169077) and {btw.loc['MMP13', 'log_ratio'] / np.log(2):+.2f} (GSE114007). "
       "Counts are out of 4 markers (SOX9, RUNX2, MMP13, CDKN2A). GSE117999 is scored with the between-joint contrast.")
    md()

    # ---------------------------------------------------------------- 4. premise test
    md("## 4. Pre-registered premise test — is OA synovium inflamed? (GSE55235 + GSE55457)")
    md()
    per = I4.contrasts()
    comb = I4.combine(per)
    for name, d in per.items():
        md(f"**{name}** (hallmark genes present: {d.attrs['hallmark_present']} / 200):")
        md()
        md(table(d, "{:.2f}"))
        md()
    md("Combined (inverse-variance):")
    md()
    md(table(comb, "{:.2f}"))
    md()
    oa_ok = comb.loc[("OA", "inflammation score"), "ci_low"] > 0
    ra_ok = comb.loc[("RA", "inflammation score"), "ci_low"] > 0
    md(f"**Premise (OA − healthy inflammation score above 0): {'supported' if oa_ok else 'NOT supported'}.** "
       f"Positive control (RA − healthy above 0): {'valid' if ra_ok else 'NOT valid'}.")
    md()

    # ---------------------------------------------------------------- 5. tissue
    md("## 5. Tissue test (OAIZIB-CM)")
    md()
    if same:
        md("Unchanged (stage-2 model).")
        md()
    else:
        cache = DERIVED / "abm_dose_response_stage5.csv"
        if cache.exists():
            dose5 = pd.read_csv(cache)
        else:
            r5 = Rates(**{k: P5[k] for k in KEYS if k not in ("baseline_runx2", "C_joint")})
            sig = np.round(np.arange(0.06, 0.3001, 0.01), 3)
            import chondrotwin.knee.erosion as E
            from chondrotwin.abm import CartilageABM, CartilageSlab, Scenario
            rows = []
            for h in (H_MED, H_LAT):
                nz = int(round(h / 0.1))
                for sg in sig:
                    for seed in (0, 1):
                        sim = CartilageABM(slab=CartilageSlab(Lx=0.4, Ly=0.4, h=h, nx=4, ny=4, nz=nz), seed=seed, rates=r5)
                        sc = Scenario("dose", sigma0=float(sg) * 1e6, days=365 * YEAR, C_joint=P5["C_joint"])
                        sim.seed_fates()
                        for d in range(sc.days):
                            sim.step(d, sc)
                            if (d + 1) % 365 == 0:
                                rows.append(dict(sigma_MPa=float(sg), h_mm=h, seed=seed, year=(d + 1) // 365,
                                                 eroded_mm=E.eroded_depth(sim.slab)))
            dose5 = pd.DataFrame(rows)
            dose5.to_csv(cache, index=False)
        geo = tibial_geometry()
        loads = L.load_all()
        mr = L.summary(loads, L.calibrate_condylar_distance(loads)).medial_ratio.values
        rows = []
        for name, dose in (("stage 2", pd.read_csv(DERIVED / "abm_dose_response_stage2.csv")), ("stage 5 (OA joint)", dose5)):
            for yr in (2, YEAR):
                r = mixture_test(geo, mr, dose, H_MED, H_LAT, yr)
                ok = r.get("calibrated", False)
                rows.append({"model": name, "ABM years": yr, "load scale (MPa)": r["load_scale_MPa"] if ok else float("nan"),
                             "predicted lateral loss (mm)": r["predicted_mean_lateral_loss_mm"] if ok else float("nan"),
                             "note": "" if ok else "no erosion at any stress yet"})
        md(table(pd.DataFrame(rows).set_index("model")))
        md()
        obs = observed_losses(geo).set_index(["split", "compartment"])
        md(f"Observed lateral loss: train {obs.loc[('train', 'lateral'), 'loss_mm']:.3f} ± {obs.loc[('train', 'lateral'), 'se_mm']:.3f}, "
           f"test {obs.loc[('test', 'lateral'), 'loss_mm']:.3f} ± {obs.loc[('test', 'lateral'), 'se_mm']:.3f} mm.")
        md()

    md("## 6. Post hoc caveat (does not change the registered result)")
    md()
    md("Woetzel et al. (2014) list *joint trauma patients* among the control group, so part of the 'healthy' synovium comes "
       "from acutely injured joints. That is consistent with IL1B and IL6 being *lower* in OA than in controls, and it makes "
       "these data a weak test of the premise in either direction: the registered result is 'not supported', not "
       "'refuted'. A cleaner test needs non-traumatic, non-arthritic control synovium.")
    md()
    md("## 7. Conclusions")
    md()
    s2 = summ.loc[tuple(float(STAGE2[k]) for k in KEYS)]
    md(f"* **Not selected.** Joint-level inflammation and inflammation-driven catabolism improve the between-joint fit "
       f"(best between-joint loss {summ[('loss_between', 'mean')].min():.0f} vs {s2[('loss_between', 'mean')]:.0f} for stage 2) "
       f"but worsen the within-joint cell fit, and the total calibration loss prefers the stage-2 model.")
    md(f"* **Premise not supported** in the pre-registered synovium test (OA − healthy inflammation score "
       f"{comb.loc[('OA', 'inflammation score'), 'diff']:+.2f} [{comb.loc[('OA', 'inflammation score'), 'ci_low']:+.2f}, "
       f"{comb.loc[('OA', 'inflammation score'), 'ci_high']:+.2f}]), with a valid RA positive control; the control group "
       f"included trauma patients (section 6).")
    b2 = between_log2(rows_of(STAGE2))
    md(f"* **The largest remaining gap is between joints:** OA vs normal cartilage shows SOX9 "
       f"{btw.loc['SOX9', 'log_ratio'] / np.log(2):+.1f} and MMP13 {btw.loc['MMP13', 'log_ratio'] / np.log(2):+.1f} log2, the "
       f"model {b2['SOX9']:+.1f} and {b2['MMP13']:+.1f}, with far more senescence. Whatever separates OA from normal joints "
       "(in these data also age and tissue source) is not captured by local overload plus SASP, and these data do not "
       "show that it is synovial inflammation.")
    md("* **Where this leaves the model:** across five stages, only the stage-2 revisions survived calibration; every "
       "later hypothesis (stages 3-5) failed to improve the calibration on the open data. Progress now needs data that are not open without an "
       "agreement (OAI longitudinal imaging and biomarkers) or new paired cartilage–synovium cohorts with non-traumatic controls.")
    md()
    md(f"_Runtime {time.perf_counter() - t0:.0f} s._")
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
